CREATE TABLE IF NOT EXISTS tbl_vnl_api_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      INTEGER      NOT NULL,
    name         VARCHAR(100) NOT NULL,
    token_hash   CHAR(64)     NOT NULL,
    abilities    JSON         DEFAULT NULL,
    last_used_at TIMESTAMP(0) DEFAULT NULL,
    expires_at   TIMESTAMP(0) DEFAULT NULL,
    created_at   TIMESTAMP(0) NOT NULL,
    revoked_at   TIMESTAMP(0) DEFAULT NULL,
    CONSTRAINT uq_api_token_hash UNIQUE (token_hash)
);
CREATE INDEX IF NOT EXISTS ix_api_token_user ON tbl_vnl_api_tokens (user_id);
