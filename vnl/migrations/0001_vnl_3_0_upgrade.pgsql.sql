-- -----------------------------------------------------------------------------
-- 1) Parola sütununu genişlet — yalnız sütun varsa ve 255'ten darsa.
--
-- bcrypt 60 karakterdir; dar sütun hash'i kırpar, kullanıcı giremez. Tür
-- değişir, NULL kabulü olduğu gibi kalır.
-- -----------------------------------------------------------------------------
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
                WHERE table_schema = current_schema()
                  AND table_name   = 'tbl_users'
                  AND column_name  = 'password'
                  AND character_maximum_length < 255) THEN
        ALTER TABLE tbl_users ALTER COLUMN password TYPE VARCHAR(255);
    END IF;
END
$$;


-- -----------------------------------------------------------------------------
-- 2) "Beni hatırla" jetonları (yalnız SHA-256 özeti saklanır)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tbl_remember_tokens (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INTEGER      NOT NULL,
    token_hash CHAR(64)     NOT NULL,
    expires_at TIMESTAMP(0) NOT NULL,
    user_agent VARCHAR(255) DEFAULT NULL,
    ip_address VARCHAR(45)  DEFAULT NULL,
    created_at TIMESTAMP(0) NOT NULL,
    used_at    TIMESTAMP(0) DEFAULT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_remember_token_hash ON tbl_remember_tokens (token_hash);
CREATE INDEX IF NOT EXISTS ix_remember_user ON tbl_remember_tokens (user_id);
CREATE INDEX IF NOT EXISTS ix_remember_expires ON tbl_remember_tokens (expires_at);


-- -----------------------------------------------------------------------------
-- 3) Yetki tablosu — yalnızca yoksa
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tbl_permissions (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    code       VARCHAR(100) NOT NULL,
    deleted_at TIMESTAMP(0) DEFAULT NULL,
    CONSTRAINT uq_permission_code UNIQUE (code)
);
