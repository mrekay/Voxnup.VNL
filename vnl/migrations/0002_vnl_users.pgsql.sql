--
-- 0002_vnl_users.sql'in karşılığı: tablolar yoksa açılır, projenin kendi
-- açtığı tablolarda eksik sütunlar eklenir (ADD COLUMN IF NOT EXISTS).
--
-- Bayraklar (is_active, totp_enabled, can_*) SMALLINT'tir, BOOLEAN değil:
-- kod 0/1 ile karşılaştırır ve PostgreSQL boolean = integer'ı reddeder.
--
-- İlk yönetici SQL ile TOHUMLANMAZ:
--   php vnl.php user:create --username=admin --super
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1) tbl_users
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tbl_users (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username         VARCHAR(64)  NOT NULL,
    password         VARCHAR(255) NOT NULL,
    name             VARCHAR(100) NOT NULL DEFAULT '',
    surname          VARCHAR(100) NOT NULL DEFAULT '',
    email            VARCHAR(190) DEFAULT NULL,
    perm_id          INTEGER      DEFAULT NULL,
    is_active        SMALLINT     NOT NULL DEFAULT 1,
    last_activity_at TIMESTAMP(0) DEFAULT NULL,
    last_login_at    TIMESTAMP(0) DEFAULT NULL,
    last_login_ip    VARCHAR(45)  DEFAULT NULL,
    totp_secret      VARCHAR(255) DEFAULT NULL,
    totp_enabled     SMALLINT     NOT NULL DEFAULT 0,
    created_at       TIMESTAMP(0) DEFAULT NULL,
    updated_at       TIMESTAMP(0) DEFAULT NULL,
    deleted_at       TIMESTAMP(0) DEFAULT NULL,
    CONSTRAINT uq_users_username UNIQUE (username)
);
CREATE INDEX IF NOT EXISTS ix_users_perm ON tbl_users (perm_id);
CREATE INDEX IF NOT EXISTS ix_users_deleted ON tbl_users (deleted_at);


-- -----------------------------------------------------------------------------
-- 2) Mevcut tbl_users — eksik sütunlar
-- -----------------------------------------------------------------------------
ALTER TABLE tbl_users ADD COLUMN IF NOT EXISTS name             VARCHAR(100) NOT NULL DEFAULT '';
ALTER TABLE tbl_users ADD COLUMN IF NOT EXISTS surname          VARCHAR(100) NOT NULL DEFAULT '';
ALTER TABLE tbl_users ADD COLUMN IF NOT EXISTS email            VARCHAR(190) DEFAULT NULL;
ALTER TABLE tbl_users ADD COLUMN IF NOT EXISTS perm_id          INTEGER      DEFAULT NULL;
ALTER TABLE tbl_users ADD COLUMN IF NOT EXISTS is_active        SMALLINT     NOT NULL DEFAULT 1;
ALTER TABLE tbl_users ADD COLUMN IF NOT EXISTS last_activity_at TIMESTAMP(0) DEFAULT NULL;
ALTER TABLE tbl_users ADD COLUMN IF NOT EXISTS last_login_at    TIMESTAMP(0) DEFAULT NULL;
ALTER TABLE tbl_users ADD COLUMN IF NOT EXISTS last_login_ip    VARCHAR(45)  DEFAULT NULL;
ALTER TABLE tbl_users ADD COLUMN IF NOT EXISTS totp_secret      VARCHAR(255) DEFAULT NULL;
ALTER TABLE tbl_users ADD COLUMN IF NOT EXISTS totp_enabled     SMALLINT     NOT NULL DEFAULT 0;
ALTER TABLE tbl_users ADD COLUMN IF NOT EXISTS created_at       TIMESTAMP(0) DEFAULT NULL;
ALTER TABLE tbl_users ADD COLUMN IF NOT EXISTS updated_at       TIMESTAMP(0) DEFAULT NULL;
ALTER TABLE tbl_users ADD COLUMN IF NOT EXISTS deleted_at       TIMESTAMP(0) DEFAULT NULL;


-- -----------------------------------------------------------------------------
-- 3) tbl_permissions — zaman damgaları (tablo 0001'de açılır)
-- -----------------------------------------------------------------------------
ALTER TABLE tbl_permissions ADD COLUMN IF NOT EXISTS created_at TIMESTAMP(0) DEFAULT NULL;
ALTER TABLE tbl_permissions ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP(0) DEFAULT NULL;


-- -----------------------------------------------------------------------------
-- 4) tbl_user_permissions — kullanıcı × yetki kodu × yetenek
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tbl_user_permissions (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       INTEGER      NOT NULL,
    permission_id INTEGER      NOT NULL,
    can_view      SMALLINT     NOT NULL DEFAULT 0,
    can_insert    SMALLINT     NOT NULL DEFAULT 0,
    can_edit      SMALLINT     NOT NULL DEFAULT 0,
    can_delete    SMALLINT     NOT NULL DEFAULT 0,
    created_at    TIMESTAMP(0) DEFAULT NULL,
    updated_at    TIMESTAMP(0) DEFAULT NULL,
    deleted_at    TIMESTAMP(0) DEFAULT NULL,
    CONSTRAINT uq_user_permission UNIQUE (user_id, permission_id)
);
CREATE INDEX IF NOT EXISTS ix_user_permission_permission ON tbl_user_permissions (permission_id);

ALTER TABLE tbl_user_permissions ADD COLUMN IF NOT EXISTS created_at TIMESTAMP(0) DEFAULT NULL;
ALTER TABLE tbl_user_permissions ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP(0) DEFAULT NULL;
ALTER TABLE tbl_user_permissions ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMP(0) DEFAULT NULL;


-- -----------------------------------------------------------------------------
-- 5) Çekirdeğin kendi yetki kodu (INSERT IGNORE karşılığı: varsa dokunulmaz;
--    ON CONFLICT yerine NOT EXISTS — projenin tablosunda code benzersiz
--    olmayabilir)
-- -----------------------------------------------------------------------------
INSERT INTO tbl_permissions (name, code, created_at, updated_at)
SELECT 'Kullanıcılar', 'Users', LOCALTIMESTAMP(0), LOCALTIMESTAMP(0)
 WHERE NOT EXISTS (SELECT 1 FROM tbl_permissions WHERE code = 'Users');
